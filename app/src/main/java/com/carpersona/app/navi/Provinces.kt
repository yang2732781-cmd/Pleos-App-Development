    JEJU("제주특별자치도", "제주", Dialect.STANDARD);

    companion object {
        /**
         * 장소 → 시·도.
         * 1) 내비가 주소를 주면 주소 맨 앞의 시·도 이름으로 (가장 정확)
         * 2) 아니면 좌표에서 가장 가까운 시·군 중심점의 시·도로
         * 바다 한가운데처럼 어느 시·군에서도 60km 넘게 떨어지면 모른다(null)고 봅니다.
         */
        fun of(p: Place?): Province? {
            p ?: return null
            p.address?.let { fromAddress(it) }?.let { return it }
            if (p.lat == null || p.lon == null) return fromAddress(p.name)
            return at(p.lat, p.lon)
        }

        fun at(lat: Double, lon: Double): Province? {
            val best = POINTS.minBy { Regions.km(lat, lon, it.lat, it.lon) }
            return if (Regions.km(lat, lon, best.lat, best.lon) <= 60) best.province else null
        }

        /** "경상북도 안동시 …", "경북 안동시", "부산 해운대구 …" 처럼 시·도 이름으로 시작하는 주소 */
        fun fromAddress(text: String): Province? {
            val head = text.trim().split(" ", limit = 2).firstOrNull() ?: return null
            return ALIASES.entries.firstOrNull { (k, _) -> head.startsWith(k) }?.value
        }

        private val ALIASES: Map<String, Province> = buildMap {
            // 긴 이름부터 (예: "광주광역시" 가 "광주"보다 먼저)
            Province.entries.forEach { put(it.label, it) }
            put("강원도", GANGWON); put("전라북도", JEONBUK); put("제주도", JEJU)
            put("서울시", SEOUL); put("인천시", INCHEON); put("대전시", DAEJEON); put("대구시", DAEGU)
            put("부산시", BUSAN); put("울산시", ULSAN); put("광주시", GWANGJU); put("세종시", SEJONG)
            put("충청도", CHUNGNAM); put("전라도", JEONNAM); put("경상도", GYEONGBUK)
            Province.entries.forEach { put(it.short, it) }
        }.entries.sortedByDescending { it.key.length }.associate { it.key to it.value }

